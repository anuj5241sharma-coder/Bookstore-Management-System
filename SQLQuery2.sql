--Advanced Queries

--1)Retrive the total number of books sold for each genre:
SELECT B.GENRE,SUM(O.quantity) AS TOTAL_BOOK_SOLD
FROM orders O
JOIN Books B ON O.Book_ID=B.Book_ID
GROUP BY Genre;

--2)FIND THE AVERAGE PRICE OF BOOKS IN THE "FANTASY" GENRE:
SELECT AVG(PRICE) AS AVERAGE_BOOK_PRICE
FROM Books
WHERE Genre='FANTASY';

--3)LIST THE CUSTOMERS WHO HAVE PLACED AT LEAST 2 ORDERS:
SELECT O.Customer_ID ,C.NAME, COUNT(O.order_id) as order_count
from orders O
JOIN customers C ON O.Customer_ID=C.Customers_ID
GROUP BY O.Customer_ID,C.Name
HAVING COUNT(ORDER_ID)>2;

--4)FIND THE MOST FREQUENTLY ORDERED BOOK:
SELECT O.BOOK_ID,B.TITLE,COUNT(O.ORDER_ID) AS ORDER_COUNT
FROM orders O
JOIN Books B ON O.Book_ID=B.Book_ID
GROUP BY O.Book_ID,B.Title
ORDER BY ORDER_COUNT DESC OFFSET 0 ROWS FETCH NEXT 1 ROWS ONLY;

--5)SHOW THE TOP 3 MOST EXPENSIVE BOOKS OF 'FANTASY' GENRE:
SELECT * FROM BOOKS
WHERE Genre='FANTASY' 
ORDER BY PRICE DESC OFFSET 0 ROWS FETCH NEXT 3 ROWS ONLY;

--6)RETRIEVE THE TOTAL QUANTITY OF BOOKS SOLD BY EACH AUTHOR:
SELECT B.AUTHOR,SUM(O.QUANTITY) AS TOTAL_BOOK_SOLD
FROM orders O
JOIN BOOKS B ON O.Book_ID=B.Book_ID
GROUP BY B.Author;

--7)LIST THE CITIES WHERE THE CUSTOMERS WHO SPENT OVER $30 ARE LOCATED:
SELECT DISTINCT C.City,O.Total_Amount
FROM orders O
JOIN customers C ON O.Customer_ID=C.Customers_ID
WHERE O.Total_Amount>30

--8)FIND THE CUSTOMER WHO SPENT MOST ON ORDERS:
SELECT C.Customers_ID, C.NAME,SUM(O.TOTAL_AMOUNT) AS MOST_SPENT
FROM orders O
JOIN customers C ON O.Customer_ID= C.Customers_ID
GROUP BY C.Customers_ID,C.Name
ORDER BY MOST_SPENT DESC OFFSET 0 ROWS FETCH NEXT 1 ROWS ONLY;

--9)CACULATE THE STOCK REMAINING AFTER FULLFILLING ALL THE ORDERS:
SELECT B.Book_ID,B.Title,B.Stock,COALESCE(SUM(O.QUANTITY),0) AS ORDER_QUANTITY,
B.STOCK-COALESCE(SUM(O.QUANTITY),0) AS REMAINING_QUANTITY
FROM Books B 
LEFT JOIN orders O ON B.Book_ID=O.Book_ID
GROUP BY B.Book_ID,B.Title,B.Stock;

